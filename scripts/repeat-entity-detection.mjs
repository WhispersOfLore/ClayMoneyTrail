#!/usr/bin/env node
// Repeat-entity detection across Investigation 001's structured data.
//
// Flags names/entities appearing 2+, 3+, or 5+ times across campaign
// finance (2020 + 2024 cycles) and the evidence ledger. Frequency is data,
// not guilt — this script assigns no score and reaches no conclusion; it
// only counts and cites. Writes REPEAT_ENTITIES.md at the project root.
//
// Run: node scripts/repeat-entity-detection.mjs
import { readFile, writeFile } from 'node:fs/promises';

const load = async (path) => JSON.parse(await readFile(new URL(path, import.meta.url), 'utf8'));

const contrib2020 = (await load('../data/investigations/campaign-contributions-2020.json')).map((c) => ({ ...c, cycle: '2020' }));
const contrib2024 = (await load('../data/investigations/campaign-contributions-2024.json')).map((c) => ({ ...c, cycle: '2023-2024' }));
const evidence = await load('../data/investigations/evidence.json');

const norm = (s) => (s ?? '').toLowerCase().trim();

const entities = new Map(); // normalized name -> { name, type, appearances: [{date, source, category}] }

const record = (name, type, date, source, category) => {
  if (!name) return;
  const key = norm(name);
  if (!key || key === 'kristen burke' || key === 'vystar credit union' || key === 'rally piryx llc') return; // exclude the candidate herself and routine bank/merchant-fee lines — not investigative signal
  if (!entities.has(key)) entities.set(key, { name, type, appearances: [] });
  entities.get(key).appearances.push({ date, source, category });
};

for (const c of [...contrib2020, ...contrib2024]) {
  record(c.contributor, c.type === 'business' ? 'BUSINESS' : c.type === 'pac' ? 'PAC' : 'PERSON', c.date, `Campaign finance (${c.cycle}, report ${c.report})`, 'campaign_finance');
}

for (const ev of evidence) {
  for (const e of ev.entities ?? []) {
    record(e, e.toLowerCase().includes('llc') || e.toLowerCase().includes('inc') || e.toLowerCase().includes('chiropractic') ? 'BUSINESS' : 'PERSON_OR_GOV', ev.date, `Evidence ${ev.id}`, 'evidence_ledger');
  }
}

const rows = [...entities.values()]
  .filter((e) => e.appearances.length >= 2)
  .map((e) => {
    const dates = e.appearances.map((a) => a.date).filter(Boolean).sort();
    const categories = [...new Set(e.appearances.map((a) => a.category))];
    const sources = [...new Set(e.appearances.map((a) => a.source))];
    return {
      name: e.name,
      type: e.type,
      count: e.appearances.length,
      first: dates[0] ?? 'undated',
      latest: dates[dates.length - 1] ?? 'undated',
      categories,
      sources,
    };
  })
  .sort((a, b) => b.count - a.count);

const tier = (n) => (n >= 5 ? '5+' : n >= 3 ? '3+' : '2+');

let md = `# Repeat Entities\n\nGenerated by \`scripts/repeat-entity-detection.mjs\` from campaign-finance data (2020 + 2023-2024 cycles) and the Evidence Ledger. **Frequency is data, not guilt** — no ranking or score is assigned; this is a raw count with citations, for a human to review.\n\n`;

for (const t of ['5+', '3+', '2+']) {
  const tierRows = rows.filter((r) => tier(r.count) === t);
  md += `## Appears ${t} times (${tierRows.length})\n\n`;
  if (!tierRows.length) {
    md += '_None at this tier._\n\n';
    continue;
  }
  md += '| Name | Type | Appearances | First date | Latest date | Categories | Sources |\n|---|---|---|---|---|---|---|\n';
  for (const r of tierRows) {
    md += `| ${r.name} | ${r.type} | ${r.count} | ${r.first} | ${r.latest} | ${r.categories.join(', ')} | ${r.sources.join('; ')} |\n`;
  }
  md += '\n';
}

md += `## Method and limits\n\nCounts contributor names across both loaded campaign-finance cycles plus every entity named in the Evidence Ledger. Does **not** yet include county vendor/contract data, property records, or BCC agenda sponsor data (none of those are loaded in structured form yet — see \`RECORDS_NEEDED.md\`), so this is necessarily an undercount of true repeat appearances. Names are matched by exact normalized string only — no fuzzy/entity-resolution matching was applied, so e.g. "Isabelle Purvis" and "Coen Purvis" are NOT merged even though they may be the same household (per this investigation's own rule against merging without confirmation).\n`;

await writeFile(new URL('../REPEAT_ENTITIES.md', import.meta.url), md, 'utf8');
console.log(`Wrote REPEAT_ENTITIES.md: ${rows.length} entities appearing 2+ times (of ${entities.size} total distinct entities tracked).`);
